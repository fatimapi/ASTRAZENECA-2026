"""Export a short stack of CT slices around each case's main nodule as JPEGs,
plus the LIDC radiologists' outlines, for the Candex imaging-review page.

Output (in the Candex repo): data/lidc/<patient>/sNN.jpg and data/lidc/cases.js
Usage: .venv/bin/python export_ct.py ~/ASTRAZENECA-2026/data/lidc
"""
import csv
import json
import sys
import warnings
from pathlib import Path
from statistics import mean

import numpy as np

warnings.filterwarnings("ignore")
for _name, _type in (("int", int), ("float", float), ("bool", bool)):
    if not hasattr(np, _name):
        setattr(np, _name, _type)
import pydicom  # noqa: E402
import pylidc as pl  # noqa: E402
from PIL import Image  # noqa: E402

SRC = Path(__file__).parent / "LIDC-IDRI"
OUT = Path(sys.argv[1])
SIZE = 384            # output pixels (from 512)
HALF = 5              # slices either side of the nodule centre -> 11 slices
LUNG_WINDOW = (-600, 1500)  # level, width

cases_meta = {r["patient_id"]: r for r in csv.DictReader(open(Path(__file__).parent / "cases.csv"))}
result = {}

for folder in sorted(p for p in SRC.iterdir() if (p / ".done").exists()):
    pid = folder.name
    slices = [pydicom.dcmread(f) for f in folder.glob("*.dcm")]
    slices = [s for s in slices if hasattr(s, "ImagePositionPatient")]
    slices.sort(key=lambda s: float(s.ImagePositionPatient[2]))
    zs = np.array([float(s.ImagePositionPatient[2]) for s in slices])
    spacing = [float(v) for v in slices[0].PixelSpacing]

    scan = pl.query(pl.Scan).filter(pl.Scan.patient_id == pid).first()
    clusters = scan.cluster_annotations(verbose=False)
    nodules = []
    for cl in clusters:
        nodules.append(dict(
            diameter=round(mean(a.diameter for a in cl), 1),
            malignancy=round(mean(a.malignancy for a in cl), 2),
            spiculation=round(mean(a.spiculation for a in cl), 2),
            texture=round(mean(a.texture for a in cl), 2),
            readers=len(cl), anns=cl))
    nodules.sort(key=lambda n: n["diameter"], reverse=True)
    main = nodules[0]

    # nodule centre: the z with the largest outlined area across readers
    area_by_z = {}
    for a in main["anns"]:
        for c in a.contours:
            pts = np.array([[float(v) for v in xy.split(",")] for xy in c.coords.strip().split("\n")])
            x, y = pts[:, 0], pts[:, 1]
            area = 0.5 * abs(np.dot(x, np.roll(y, 1)) - np.dot(y, np.roll(x, 1)))
            area_by_z[c.image_z_position] = area_by_z.get(c.image_z_position, 0) + area
    zc = max(area_by_z, key=area_by_z.get)
    k = int(np.argmin(abs(zs - zc)))
    ks = list(range(max(0, k - HALF), min(len(slices), k + HALF + 1)))

    out_dir = OUT / pid
    out_dir.mkdir(parents=True, exist_ok=True)
    level, width = LUNG_WINDOW
    lo, hi = level - width / 2, level + width / 2
    frames = []
    for i, kk in enumerate(ks):
        s = slices[kk]
        hu = s.pixel_array.astype(np.float32) * float(s.RescaleSlope) + float(s.RescaleIntercept)
        img = np.clip((hu - lo) / (hi - lo) * 255, 0, 255).astype(np.uint8)
        Image.fromarray(img).resize((SIZE, SIZE), Image.LANCZOS).save(out_dir / f"s{i:02d}.jpg", quality=82, optimize=True)
        # outlines from every reader of every nodule on this slice
        outlines = []
        for ni, nod in enumerate(nodules):
            for a in nod["anns"]:
                for c in a.contours:
                    if abs(c.image_z_position - zs[kk]) < 0.01 and c.inclusion:
                        pts = [[float(v) for v in xy.split(",")] for xy in c.coords.strip().split("\n")]
                        outlines.append({"n": ni, "pts": [[round(x * SIZE / 512, 1), round(y * SIZE / 512, 1)] for x, y in pts]})
        frames.append({"src": f"data/lidc/{pid}/s{i:02d}.jpg", "z": round(float(zs[kk]), 2), "outlines": outlines})

    meta = cases_meta[pid]
    result[pid] = {
        "id": pid, "band": meta["band"], "slices": len(slices), "sliceMm": float(slices[0].SliceThickness),
        "pixelMm": round(spacing[0], 3), "centre": ks.index(k), "frames": frames,
        "nodules": [{k2: v for k2, v in n.items() if k2 != "anns"} for n in nodules],
    }
    print(pid, meta["band"], f"{len(nodules)} nodules, main {main['diameter']} mm, slices {ks[0]}-{ks[-1]} of {len(slices)},",
          sum(len(f["outlines"]) for f in frames), "outlines")

(OUT / "cases.js").write_text(
    "// Generated by candex-data/export_ct.py from the public LIDC-IDRI collection (CC BY 3.0).\n"
    "// Armato SG III et al. Med Phys 2011;38(2):915-931. doi:10.1118/1.3528204. Data from The Cancer Imaging Archive.\n"
    f"window.candexLidc = {json.dumps(result, separators=(',', ':'))};\n")
print("wrote", OUT / "cases.js")
