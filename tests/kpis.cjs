const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const path=require('node:path');
const sandbox={window:{},localStorage:{getItem(){return null},setItem(){}}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../kpis.js'),'utf8'),sandbox);
const api=sandbox.window.CandexKpis;
assert.equal(api.evaluate('referral_review_days',14).level,'green');
assert.equal(api.evaluate('referral_review_days',15).level,'yellow');
assert.equal(api.evaluate('referral_review_days',21).level,'yellow');
assert.equal(api.evaluate('referral_review_days',22).level,'red');
assert.equal(api.evaluate('referral_review_days',12,{applicable:false}).level,'unknown');
assert.equal(api.evaluate('referral_review_days',null).level,'unknown');
assert.equal(api.evaluate('screening_participation',80).level,'green');
assert.equal(api.evaluate('screening_participation',70).level,'yellow');
assert.equal(api.evaluate('screening_participation',69).level,'red');
assert.equal(api.evaluate('early_stage_share',70).level,'green');
assert.equal(api.evaluate('early_stage_share',60).level,'yellow');
assert.equal(api.evaluate('early_stage_share',59).level,'red');
assert.equal(api.evaluate('early_stage_share',101).level,'unknown');
for(const id of ['diagnosis_days','false_positive_rate','detection_sensitivity','followup_completion','data_completeness','specialist_assessment_days','treatment_wait_days'])assert.equal(api.evaluate(id,20).level,'unknown');
assert(api.evaluate('referral_review_days',18).basis.includes('local bands'));
assert(api.evaluate('screening_participation',75).basis.includes('not national clinical alarms'));
api.setMode('demo');
assert.equal(api.evaluate('diagnosis_days',24).level,'yellow');
assert.equal(api.evaluate('followup_completion',98).level,'green');
assert.equal(api.evaluate('followup_completion',70).level,'red');
assert(api.evaluate('diagnosis_days',24).thresholdLabel.includes('LOCAL DEMO'));
assert.equal(api.evaluate('made-up',1).level,'unknown');
assert.throws(()=>api.setMode('unverified'));
console.log('PASS: sourced KPI boundaries, explicit local warnings, unsupported/missing-data neutrality and demo-mode separation.');

